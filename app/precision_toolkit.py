"""
MedStruct v3 (1) Precision Toolkit.
Implements the exact precision post-processing pipeline from medstruct_nlp_v3 (1).ipynb:
1. Temperature Scaling Calibration: fitted on dev to ensure probabilities represent true confidence.
2. Order-Aware Markov Decoding: HMM-style forward-backward sequence modeling using RCT transition
   priors, start priors, and label priors to correct sentence-level misclassifications.
3. Class-Calibrated Selective Abstention: per-role confidence thresholds derived on dev to guarantee
   target precision (e.g. >= 90% for OBJECTIVE, METHODS, RESULTS), flagging uncertain sentences as
   NEEDS REVIEW (UNSURE) without forcing false classifications.
"""

import os
import json
from typing import Dict, Any, Tuple, List, Optional
import numpy as np
from scipy.special import logsumexp

LABELS = ['BACKGROUND', 'OBJECTIVE', 'METHODS', 'RESULTS', 'CONCLUSIONS']
NC = len(LABELS)
L2I = {l: i for i, l in enumerate(LABELS)}

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_CONFIG_PATH = os.path.join(BASE_DIR, 'medstruct', 'results', 'precision_config.json')

_CACHED_CONFIG: Optional[Dict[str, Any]] = None

def load_precision_config(config_path: Optional[str] = None) -> Dict[str, Any]:
    """
    Loads precision configuration generated by medstruct_nlp_v3 (1).ipynb.
    Falls back to sensible defaults if file is not found.
    """
    global _CACHED_CONFIG
    path = config_path or DEFAULT_CONFIG_PATH
    if _CACHED_CONFIG is not None and not config_path:
        return _CACHED_CONFIG

    if os.path.exists(path):
        with open(path, 'r', encoding='utf-8') as f:
            cfg = json.load(f)
        for k in ('logT', 'logS', 'logP'):
            if k in cfg and not isinstance(cfg[k], np.ndarray):
                cfg[k] = np.array(cfg[k], dtype=np.float64)
        _CACHED_CONFIG = cfg
        return cfg

    # Fallback default configuration matching v3 (1) empirical fit on PubMed RCT
    default_cfg = {
        "run_ids": ["tfidf"],
        "T": 1.0,
        "lam": 0.75,
        "beta": 0.5,
        "target": 0.90,
        "th": {
            "BACKGROUND": 0.98965,
            "OBJECTIVE": 0.86738,
            "METHODS": 0.35439,
            "RESULTS": 0.31055,
            "CONCLUSIONS": 0.28081
        },
        "logT": np.array([
            [-0.51609, -2.34004, -1.24307, -4.01366, -8.24486],
            [-4.08021, -1.14255, -0.42989, -4.34815, -7.45609],
            [-6.32405, -6.89315, -0.28308, -1.47306, -4.23289],
            [-8.66306, -10.96564, -7.74677, -0.27659, -1.42291],
            [-1.75393, -7.14414, -4.31584, -7.54961, -0.20796]
        ], dtype=np.float64),
        "logS": np.array([-0.70853, -0.69055, -5.23411, -9.61614, -6.97708], dtype=np.float64),
        "logP": np.array([-2.11461, -2.56564, -1.10969, -1.13356, -1.89113], dtype=np.float64)
    }
    _CACHED_CONFIG = default_cfg
    return default_cfg

def apply_temperature(probs: np.ndarray, T: float) -> np.ndarray:
    """
    Applies temperature scaling calibration: p_calibrated = softmax(log(p) / T).
    From medstruct_nlp_v3 (1).ipynb cell 40.
    """
    if T <= 0 or abs(T - 1.0) < 1e-6:
        return probs
    lp = np.log(np.clip(probs, 1e-9, 1.0)) / T
    return np.exp(lp - logsumexp(lp, axis=1, keepdims=True))

def posterior_marginals(
    probs: np.ndarray,
    abstract_ids: np.ndarray,
    logT: np.ndarray,
    logStart: np.ndarray,
    logPrior: np.ndarray,
    lam: float = 1.0,
    beta: float = 1.0
) -> np.ndarray:
    """
    HMM forward-backward over sentences within each abstract.
    Corrects sentence-level predictions by enforcing RCT rhetorical sequence structure.
    From medstruct_nlp_v3 (1).ipynb cell 40.
    """
    if lam == 0 and beta == 0:
        return probs.copy()

    out = np.zeros_like(probs)
    ids = np.asarray(abstract_ids)
    if len(ids) == 0:
        return out

    cuts = np.r_[0, np.flatnonzero(ids[1:] != ids[:-1]) + 1, len(ids)]
    E = np.log(np.clip(probs, 1e-9, 1.0)) - beta * logPrior
    Tr = lam * logT
    St = lam * logStart

    for a, b in zip(cuts[:-1], cuts[1:]):
        e = E[a:b]
        n = b - a
        al = np.zeros((n, NC))
        be = np.zeros((n, NC))
        al[0] = St + e[0]
        for t in range(1, n):
            al[t] = logsumexp(al[t - 1][:, None] + Tr, axis=0) + e[t]
        for t in range(n - 2, -1, -1):
            be[t] = logsumexp(Tr + (e[t + 1] + be[t + 1])[None, :], axis=1)
        post = al + be
        out[a:b] = np.exp(post - logsumexp(post, axis=1, keepdims=True))
    return out

def apply_thresholds(marg: np.ndarray, th: Dict[str, float]) -> np.ndarray:
    """
    Applies calibrated abstention thresholds. Sentences whose winning class confidence
    falls below that class's target-precision threshold are labeled 'UNSURE'.
    From medstruct_nlp_v3 (1).ipynb cell 40.
    """
    pred = np.array(LABELS)[marg.argmax(axis=1)]
    conf = marg.max(axis=1)
    keep = np.array([conf[i] >= th.get(pred[i], 0.5) for i in range(len(pred))])
    return np.where(keep, pred, 'UNSURE')
